"""Qt-side fixtures: labelled test tiles (obviously synthetic), screenshot helper, scripted dialogs."""

import os
from pathlib import Path

from PySide6.QtCore import QBuffer, QByteArray, QIODevice, QRectF, Qt
from PySide6.QtGui import QColor, QFont, QImage, QPainter, QPen

from mapfix import tile_color
from task_maps import mbtiles


def labelled_png(z, x, y, size=256) -> bytes:
    img = QImage(size, size, QImage.Format.Format_RGB32)
    img.fill(QColor(*tile_color(z, x, y)))
    p = QPainter(img)
    p.setPen(QPen(QColor(255, 255, 255, 120), 1))
    p.drawRect(0, 0, size - 1, size - 1)
    f = QFont()
    f.setPixelSize(16)
    p.setFont(f)
    p.setPen(QColor(255, 255, 255))
    p.drawText(QRectF(0, size / 2 - 30, size, 60), Qt.AlignmentFlag.AlignCenter, f"TEST FIXTURE\n{z}/{x}/{y}")
    p.end()
    ba = QByteArray()
    buf = QBuffer(ba)
    buf.open(QIODevice.OpenModeFlag.WriteOnly)
    img.save(buf, "PNG")
    return bytes(ba)


def labelled_mbtiles(path, tiles, attribution="TEST FIXTURE tiles (generated by the test suite)", name="Fixture"):
    mbtiles.create(path, {"name": name, "format": "png", "attribution": attribution, "type": "baselayer",
                          "minzoom": str(min(t[0] for t in tiles)), "maxzoom": str(max(t[0] for t in tiles))})
    w = mbtiles.TileWriter(path)
    w.start()
    for z, x, y in tiles:
        w.put(mbtiles.Write(z, x, y, labelled_png(z, x, y)))
    assert w.flush(60)
    w.stop()
    return Path(path)


def shot_dir(tmp_path):
    d = os.environ.get("TASK_MAPS_SCREENSHOTS")
    p = Path(d) if d else tmp_path / "shots"
    p.mkdir(parents=True, exist_ok=True)
    return p


class ScriptedDialogs:
    def __init__(self, confirm=True, open_path="", save_path="", text=None, secret=None):
        self.answers = {"confirm": confirm}
        self.open_path, self.save_path, self.text_value, self.secret_value = open_path, save_path, text, secret
        self.log = []

    def confirm(self, title, text):
        self.log.append(("confirm", title, text))
        a = self.answers["confirm"]
        return a.pop(0) if isinstance(a, list) else a

    def inform(self, title, text):
        self.log.append(("inform", title, text))

    def open_file(self, title, filt):
        self.log.append(("open", title))
        return self.open_path

    def save_file(self, title, name, filt):
        self.log.append(("save", title))
        return self.save_path

    def text(self, title, label, value=""):
        self.log.append(("text", title, value))
        return self.text_value

    def secret(self, title, label):
        self.log.append(("secret", title))
        return self.secret_value
