class FakeCore:
    """Unix-socket rain-core v2 stand-in answering capability.list."""

    def __init__(self, path, status="no-provider"):
        self.path = str(path)
        self.status = status
        self.requests = []
        self.sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        self.sock.bind(self.path)
        os.chmod(self.path, 0o600)
        self.sock.listen(4)
        threading.Thread(target=self._loop, daemon=True).start()

    def _loop(self):
        while True:
            try:
                c, _ = self.sock.accept()
            except OSError:
                return
            with c:
                buf = b""
                while b"\n" not in buf:
                    d = c.recv(4096)
                    if not d:
                        break
                    buf += d
                if not buf:
                    continue
                req = json.loads(buf.split(b"\n")[0])
                self.requests.append(req)
                res = {"capabilities": [{"name": "gps.position", "kind": "sensor", "status": self.status},
                                        {"name": "radio.rx", "kind": "radio", "status": "no-device"}]}
                c.sendall(json.dumps({"v": 2, "id": req.get("id"), "ok": True, "result": res}).encode() + b"\n")

    def close(self):
        self.sock.close()
