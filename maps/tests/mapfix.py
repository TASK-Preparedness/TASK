class TileServer:
    """Loopback XYZ tile server ``/tiles/{z}/{x}/{y}.png`` with scripted failures.

    * ``script[(z,x,y)]`` -> list of responses consumed in order: int status, ``("429", seconds)``,
      ``"corrupt"``, ``"drop"`` (close the connection without a response), ``"slow"``.
    * ``global_429`` -> number of initial requests answered 429 with ``retry_after``.
    * ``down`` -> when True every request is dropped (simulated network loss).
    Records request times, user agents, paths and the maximum concurrency."""

    def __init__(self, delay=0.0):
        self.script = {}
        self.global_429 = 0
        self.retry_after = "1"
        self.down = False
        self.delay = delay
        self.requests = []          # (monotonic time, path, ua)
        self.max_conc = 0
        self._conc = 0
        self._lock = threading.Lock()
        self.status_default = 200
        outer = self

        class H(BaseHTTPRequestHandler):
            protocol_version = "HTTP/1.0"

            def log_message(self, *a):
                pass

            def do_GET(self):
                outer._handle(self)

        self.httpd = ThreadingHTTPServer(("127.0.0.1", 0), H)
        self.httpd.daemon_threads = True
        self.port = self.httpd.server_address[1]
        LOCAL_ALLOWED_PORTS.add(self.port)
        self.url = f"http://127.0.0.1:{self.port}/tiles/{{z}}/{{x}}/{{y}}.png"

    def start(self):
        self._started = True
        threading.Thread(target=self.httpd.serve_forever, daemon=True).start()

    def stop(self):
        if getattr(self, "_started", False):
            self.httpd.shutdown()
        self.httpd.server_close()
        LOCAL_ALLOWED_PORTS.discard(self.port)

    def tile_requests(self):
        return [r for r in self.requests if r[1].startswith("/tiles/")]

    def _handle(self, h):
        with self._lock:
            self._conc += 1
            self.max_conc = max(self.max_conc, self._conc)
            self.requests.append((time.monotonic(), h.path, h.headers.get("User-Agent", "")))
            g429 = self.global_429 > 0
            if g429:
                self.global_429 -= 1
        try:
            if self.down:
                h.close_connection = True
                h.connection.shutdown(socket.SHUT_RDWR)
                return
            if self.delay:
                time.sleep(self.delay)
            parts = h.path.split("/")
            try:
                z, x, y = int(parts[2]), int(parts[3]), int(parts[4].split(".")[0])
            except (IndexError, ValueError):
                return self._send(h, 400, b"bad")
            if g429:
                return self._send(h, 429, b"slow down", {"Retry-After": self.retry_after})
            todo = self.script.get((z, x, y))
            action = todo.pop(0) if todo else self.status_default
            if action == "drop":
                h.connection.shutdown(socket.SHUT_RDWR)
                return
            if action == "corrupt":
                return self._send(h, 200, b"\x89PNG\r\n\x1a\n" + b"garbage" * 20, {"Content-Type": "image/png"})
            if isinstance(action, tuple) and action[0] == "429":
                return self._send(h, 429, b"", {"Retry-After": str(action[1])})
            if action == 200:
                return self._send(h, 200, make_png(tile_color(z, x, y), 64), {"Content-Type": "image/png"})
            return self._send(h, int(action), b"error")
        finally:
            with self._lock:
                self._conc -= 1

    @staticmethod
    def _send(h, status, body, headers=None):
        h.send_response(status)
        for k, v in (headers or {}).items():
            h.send_header(k, v)
        h.send_header("Content-Length", str(len(body)))
        h.end_headers()
        h.wfile.write(body)


class FakeGpsd:
    """Loopback gpsd speaking the JSON protocol. Records everything clients send."""

    def __init__(self, port=0):
        self.received = []
        self.clients = []
        self.on_watch = []           # lines to send after ?WATCH
        self._lock = threading.Lock()
        outer = self

        class H(socketserver.BaseRequestHandler):
            def handle(self):
                outer._client(self.request)

        socketserver.ThreadingTCPServer.allow_reuse_address = True
        self.srv = socketserver.ThreadingTCPServer(("127.0.0.1", port), H)
        self.srv.daemon_threads = True
        self.port = self.srv.server_address[1]
        LOCAL_ALLOWED_PORTS.add(self.port)

    def start(self):
        threading.Thread(target=self.srv.serve_forever, daemon=True).start()

    def stop(self):
        self.srv.shutdown()
        self.srv.server_close()
        self.drop_clients()
        LOCAL_ALLOWED_PORTS.discard(self.port)

    def _client(self, conn):
        with self._lock:
            self.clients.append(conn)
        conn.sendall(b'{"class":"VERSION","release":"3.25","rev":"3.25","proto_major":3,"proto_minor":15}\n')
        buf = b""
        try:
            while True:
                d = conn.recv(4096)
                if not d:
                    break
                buf += d
                while b"\n" in buf:
                    line, buf = buf.split(b"\n", 1)
                    self.received.append(line)
                    if line.startswith(b"?WATCH"):
                        conn.sendall(b'{"class":"DEVICES","devices":[{"class":"DEVICE","path":"/dev/ttyACM0",'
                                     b'"driver":"u-blox","activated":"2026-10-10T00:00:00.000Z"}]}\n')
                        for m in self.on_watch:
                            conn.sendall(json.dumps(m).encode() + b"\n")
        except OSError:
            pass

    def send(self, msg: dict):
        data = json.dumps(msg).encode() + b"\n"
        with self._lock:
            for c in list(self.clients):
                try:
                    c.sendall(data)
                except OSError:
                    self.clients.remove(c)

    def drop_clients(self):
        with self._lock:
            for c in self.clients:
                try:
                    c.shutdown(socket.SHUT_RDWR)
                    c.close()
                except OSError:
                    pass
            self.clients.clear()


