def make_png(rgb=(40, 90, 160), size=256) -> bytes:
    """A real, decodable solid-colour RGB PNG (pure Python, deterministic)."""
    w = h = size
    raw = b"".join(b"\x00" + bytes(rgb) * w for _ in range(h))

    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def tile_color(z, x, y):
    return ((37 * x + 11 * z) % 200 + 30, (53 * y + 7 * z) % 200 + 30, (19 * (x + y) + 90) % 200 + 30)


def make_mbtiles(path, zooms=(0, 1, 2), color=tile_color, metadata=None, bbox_tiles=None):
    """Build an MBTiles file with every tile of the given zooms (or only ``bbox_tiles`` (z,x,y) list)."""
    md = {"name": "Fixture", "format": "png", "attribution": "Test fixture tiles", "type": "baselayer",
          "version": "1.0", "description": "generated by tests"}
    md.update(metadata or {})
    tiles = bbox_tiles or [(z, x, y) for z in zooms for x in range(2 ** z) for y in range(2 ** z)]
    md.setdefault("minzoom", str(min(t[0] for t in tiles)))
    md.setdefault("maxzoom", str(max(t[0] for t in tiles)))
    mbtiles.create(path, md)
    w = mbtiles.TileWriter(path)
    w.start()
    for z, x, y in tiles:
        w.put(mbtiles.Write(z, x, y, make_png(color(z, x, y), 64)))
    assert w.flush(30)
    w.stop()
    return Path(path)


